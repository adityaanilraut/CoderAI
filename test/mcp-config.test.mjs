import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fixture } from './fixture.mjs';

test('MCP CLI manages user configuration and preserves project configuration', { timeout: 40000 }, async t => {
  const f = await fixture(); t.after(f.cleanup);
  const configPath = join(f.root, 'server.json');
  await writeFile(configPath, JSON.stringify({ command: process.execPath, args: ['test-server.js'], env: { API_SECRET: 'secret-value' } }));
  const added = await f.run(['mcp', 'add', 'example', configPath]);
  assert.equal(added.code, 0, added.stderr);
  const listed = await f.run(['mcp', 'list']);
  assert.equal(listed.code, 0, listed.stderr); assert.match(listed.stdout, /example/);
  assert.doesNotMatch(listed.stdout, /secret-value/);
  const duplicate = await f.run(['mcp', 'add', 'example', configPath]);
  assert.equal(duplicate.code, 1);
  await writeFile(configPath, JSON.stringify({ url: 'https://example.test/mcp?token=private-value', headers: { Authorization: 'secret-header' } }));
  const updated = await f.run(['mcp', 'update', 'example', configPath]);
  assert.equal(updated.code, 0, updated.stderr);
  const updatedList = await f.run(['mcp', 'list']);
  assert.match(updatedList.stdout, /example\.test/);
  assert.doesNotMatch(updatedList.stdout, /private-value|secret-header/);
  await mkdir(join(f.cwd, '.coderai'));
  const projectPath = join(f.cwd, '.coderai', 'mcp.json');
  const project = JSON.stringify({ mcpServers: { project: { command: 'node', args: ['project-server.js'] } } });
  await writeFile(projectPath, project);
  const untrusted = await f.run(['mcp', 'list']);
  assert.doesNotMatch(untrusted.stdout, /^project\t/m);
  assert.match(untrusted.stdout, /Project servers are hidden/);
  const withProject = await f.run(['--trust', 'mcp', 'list']);
  assert.match(withProject.stdout, /project/); assert.match(withProject.stdout, /read-only/);
  const removed = await f.run(['mcp', 'remove', 'example']);
  assert.equal(removed.code, 0, removed.stderr);
  assert.equal(await readFile(projectPath, 'utf8'), project);
  const remaining = await f.run(['mcp', 'list']);
  assert.doesNotMatch(remaining.stdout, /example/); assert.match(remaining.stdout, /project/);
  await writeFile(configPath, '{broken');
  const invalid = await f.run(['mcp', 'add', 'invalid', configPath]);
  assert.equal(invalid.code, 1); assert.match(invalid.stderr, /JSON/);
});
