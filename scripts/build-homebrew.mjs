import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

const { values } = parseArgs({ options: {
  version: { type: 'string' },
  'assets-dir': { type: 'string', default: 'dist-bun' },
  output: { type: 'string', default: 'dist-bun/coderai.rb' },
} });
const version = values.version ?? JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8')).version;
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('Homebrew requires a stable release version (for example, 0.6.0).');

const checksums = new Map();
for (const target of ['darwin-arm64', 'darwin-x64', 'linux-arm64', 'linux-x64']) {
  const name = `coderai-bun-${target}.zip`;
  const archive = join(values['assets-dir'], name);
  const checksum = (await readFile(`${archive}.sha256`, 'utf8')).trim();
  const match = /^([a-f0-9]{64}) {2}(\S+)$/.exec(checksum);
  if (!match || match[2] !== name) throw new Error(`Invalid checksum file for ${name}`);
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(archive)) hash.update(chunk);
  if (hash.digest('hex') !== match[1]) throw new Error(`Checksum mismatch for ${name}`);
  checksums.set(target, match[1]);
}

const platform = (os, arch) => `    on_${arch === 'arm64' ? 'arm' : 'intel'} do
      url "https://github.com/adityaanilraut/CoderAI/releases/download/v${version}/coderai-bun-${os}-${arch}.zip"
      sha256 "${checksums.get(`${os}-${arch}`)}"
    end`;
const formula = `# frozen_string_literal: true

# Generated by scripts/build-homebrew.mjs from verified release archives.
class Coderai < Formula
  desc "Terminal coding assistant powered by configurable AI models"
  homepage "https://github.com/adityaanilraut/CoderAI"
  version "${version}"
  license "MIT"

  depends_on "ripgrep"

  on_macos do
${platform('darwin', 'arm64')}
${platform('darwin', 'x64')}
  end

  on_linux do
${platform('linux', 'arm64')}
${platform('linux', 'x64')}
  end

  def install
    bin.install "coderai"
    prefix.install "NOTICE", "LICENSE.pi-tui", "LICENSE.jsquash-webp", "LICENSE.libwebp"
  end

  def caveats
    <<~EOS
      Run coderai --setup to configure your model provider.
    EOS
  end

  test do
    ENV["CODERAI_HOME"] = testpath/"home"
    assert_match version.to_s, shell_output("#{bin}/coderai --version")
    assert_match "Usage:", shell_output("#{bin}/coderai --help")
  end
end
`;
const output = resolve(values.output);
await mkdir(dirname(output), { recursive: true });
await writeFile(output, formula);
console.log(`Generated ${output} for CoderAI ${version}`);
